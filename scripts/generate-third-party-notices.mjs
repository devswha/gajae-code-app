/**
 * Collects the notices this project owes for the code it redistributes.
 *
 * Every distribution carries hundreds of third-party packages, and most of
 * their licenses require their copyright and permission text to travel with
 * them. Two of those obligations were being missed outright: the bundled GJC
 * runtime declares MIT but ships no license file, and Pretendard is OFL-1.1
 * whose subset fonts land in `dist/assets` with the license nowhere near them.
 *
 * A hand-maintained list would answer for today's tree and quietly stop being
 * true on the next `npm install`, so this reads the tree instead. Packages the
 * build removes are skipped, because a notice for something that does not ship
 * is noise that makes the real entries harder to trust.
 *
 * Usage:
 *   node scripts/generate-third-party-notices.mjs           write the file
 *   node scripts/generate-third-party-notices.mjs --check   fail when stale
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { EXCLUDED_FROM_DISTRIBUTION } from './release/distribution-exclusions.mjs';

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = join(REPOSITORY_ROOT, 'THIRD-PARTY-NOTICES.md');
const excluded = new Set(EXCLUDED_FROM_DISTRIBUTION.map((entry) => entry.package));

/** Where license text hides. Package root first, then the directories that ship assets. */
const LICENSE_DIRECTORIES = ['', 'dist', 'lib', 'src'];
const LICENSE_FILE = /^(licen[cs]e|copying|notice|ofl)([.-].*)?$/i;

function findLicenseText(installPath) {
  for (const directory of LICENSE_DIRECTORIES) {
    const base = join(REPOSITORY_ROOT, installPath, directory);
    if (!existsSync(base)) continue;
    let entries;
    try {
      entries = readdirSync(base, { withFileTypes: true });
    } catch {
      continue;
    }
    const match = entries.find((entry) => entry.isFile() && LICENSE_FILE.test(entry.name));
    if (!match) continue;
    try {
      const text = readFileSync(join(base, match.name), 'utf8').trim();
      if (text) return { text, source: join(directory, match.name).replace(/^\//u, '') };
    } catch {
      // Unreadable: reported as missing below rather than guessed at.
    }
  }
  return undefined;
}

function manifestOf(installPath) {
  try {
    return JSON.parse(readFileSync(join(REPOSITORY_ROOT, installPath, 'package.json'), 'utf8'));
  } catch {
    return {};
  }
}

function authorOf(manifest) {
  const author = manifest.author;
  if (typeof author === 'string') return author;
  if (author && typeof author === 'object' && typeof author.name === 'string') return author.name;
  const contributors = Array.isArray(manifest.contributors) ? manifest.contributors : [];
  const first = contributors.find((entry) => typeof entry === 'string' || entry?.name);
  if (typeof first === 'string') return first;
  if (first?.name) return first.name;
  return undefined;
}

function collect() {
  const lock = JSON.parse(readFileSync(join(REPOSITORY_ROOT, 'package-lock.json'), 'utf8'));
  const packages = new Map();
  for (const [installPath, entry] of Object.entries(lock.packages ?? {})) {
    if (!installPath.startsWith('node_modules/')) continue;
    if (entry.dev || entry.devOptional) continue;
    const name = installPath.slice(installPath.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (excluded.has(name)) continue;
    // A package installed at several depths is one obligation, not several.
    if (packages.has(name)) continue;
    const manifest = manifestOf(installPath);
    packages.set(name, {
      name,
      version: entry.version ?? manifest.version ?? 'unknown',
      license: entry.license ?? manifest.license ?? 'UNKNOWN',
      author: authorOf(manifest),
      homepage: typeof manifest.homepage === 'string' ? manifest.homepage : undefined,
      license_text: findLicenseText(installPath),
    });
  }
  return [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function render(entries) {
  const withoutText = entries.filter((entry) => !entry.license_text);
  const lines = [
    '# Third-party notices',
    '',
    '<!--',
    '  GENERATED by scripts/generate-third-party-notices.mjs - do not edit.',
    '  Regenerate with `npm run generate:notices`; `npm run verify` fails when this',
    '  file no longer matches the dependency tree.',
    '-->',
    '',
    'Gajae Code App redistributes the packages below. Their licenses are reproduced',
    'here because most of them require it, and because a user who receives a build',
    'has no other way to find out what is inside it.',
    '',
    `This file describes ${entries.length} packages that ship in a distribution.`,
    'Development-only dependencies are excluded because they do not.',
    '',
  ];

  if (excluded.size > 0) {
    lines.push(
      'Deliberately absent: '
      + [...excluded].map((name) => `\`${name}\``).join(', ')
      + '. The build removes them from every distribution, so this project does not',
      'redistribute them. See `scripts/release/distribution-exclusions.mjs`.',
      '',
    );
  }

  if (withoutText.length > 0) {
    lines.push(
      '## Packages that ship no license file',
      '',
      'These declare a license in their manifest but do not include its text. The',
      'declaration and the attribution are reproduced; the full terms are the',
      'standard text of the named license.',
      '',
      '| Package | Version | License | Copyright holder |',
      '| --- | --- | --- | --- |',
      ...withoutText.map((entry) => `| \`${entry.name}\` | ${entry.version} | ${entry.license} | ${entry.author ?? '(not stated)'} |`),
      '',
    );
  }

  lines.push('## Licenses', '');
  for (const entry of entries) {
    lines.push(`### ${entry.name} ${entry.version}`, '');
    lines.push(`License: ${entry.license}`);
    if (entry.author) lines.push(`Copyright holder: ${entry.author}`);
    if (entry.homepage) lines.push(`Homepage: ${entry.homepage}`);
    lines.push('');
    if (entry.license_text) {
      lines.push('```text', entry.license_text.text, '```', '');
    } else {
      lines.push(
        `_This package ships no license file. It declares ${entry.license}; the terms are`,
        'the standard text of that license._',
        '',
      );
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const entries = collect();
const rendered = render(entries);
const checkOnly = process.argv.includes('--check');

if (!checkOnly) {
  writeFileSync(OUTPUT_PATH, rendered);
  const missing = entries.filter((entry) => !entry.license_text).length;
  console.log(
    `Wrote THIRD-PARTY-NOTICES.md for ${entries.length} shipped packages `
    + `(${missing} declare a license without shipping its text).`,
  );
} else if (!existsSync(OUTPUT_PATH)) {
  console.error('THIRD-PARTY-NOTICES.md is missing. Run `npm run generate:notices`.');
  process.exitCode = 1;
} else if (readFileSync(OUTPUT_PATH, 'utf8') !== rendered) {
  console.error(
    'THIRD-PARTY-NOTICES.md no longer matches the dependency tree.\n'
    + 'Run `npm run generate:notices` and commit the result.',
  );
  process.exitCode = 1;
} else {
  console.log(`THIRD-PARTY-NOTICES.md matches the dependency tree (${entries.length} packages).`);
}
